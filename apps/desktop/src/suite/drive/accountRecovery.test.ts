import { afterEach, expect, it, vi } from "vite-plus/test";
import { createDriveAccountRecovery } from "./accountRecovery.ts";
afterEach(() => vi.useRealTimers());
it("backs off successful attempts, caps recovery, and stops after a failed sync", async () => {
  vi.useFakeTimers();
  const renew = vi.fn(async () => {});
  const reload = vi.fn();
  const recovery = createDriveAccountRecovery({ renew, reload, trace: vi.fn() });
  await recovery.recover();
  await recovery.recover();
  expect(renew).toHaveBeenCalledTimes(1);
  vi.advanceTimersByTime(60_000);
  await recovery.recover();
  vi.advanceTimersByTime(120_000);
  await recovery.recover();
  vi.advanceTimersByTime(240_000);
  await recovery.recover();
  expect(renew).toHaveBeenCalledTimes(3);
  expect(reload).toHaveBeenCalledTimes(3);
  recovery.healthy();
  renew.mockRejectedValueOnce(new Error("offline"));
  await recovery.recover();
  vi.advanceTimersByTime(900_000);
  await recovery.recover();
  expect(renew).toHaveBeenCalledTimes(4);
  expect(reload).toHaveBeenCalledTimes(3);
});
it("deduplicates concurrent recovery and does not reset its budget while a sync is pending", async () => {
  const pending = Promise.withResolvers<void>();
  const renew = vi.fn(() => pending.promise);
  const recovery = createDriveAccountRecovery({ renew, reload: vi.fn(), trace: vi.fn() });
  const first = recovery.recover();
  recovery.healthy();
  await recovery.recover();
  pending.resolve();
  await first;
  await recovery.recover();
  expect(renew).toHaveBeenCalledTimes(1);
});
